namespace System.Curl.Http
{
    /// <summary>
    /// Определяет, в какой момент асинхронная операция <see cref="HttpClient.SendAsync"/>
    /// считается завершённой.
    /// </summary>
    public enum HttpCompletionOption
    {
        /// <summary>
        /// Операция завершается после полного чтения тела ответа (включая содержимое).
        /// Значение по умолчанию.
        /// </summary>
        /// <remarks>
        /// При этом варианте <c>SendAsync</c> возвращает управление только после того,
        /// как весь ответ получен и помещён в буфер. Удобно для небольших ответов
        /// (JSON API, короткие тексты).
        /// </remarks>
        ResponseContentRead = 0,

        /// <summary>
        /// Операция завершается сразу после получения заголовков ответа.
        /// Тело доступно для чтения по мере поступления.
        /// </summary>
        /// <remarks>
        /// При этом варианте <c>SendAsync</c> возвращает управление, как только
        /// получены заголовки. Тело можно читать через <c>response.Content.ReadAsStreamAsync()</c>.
        /// Полезно для больших ответов, SSE-стриминга, скачивания файлов.
        /// </remarks>
        ResponseHeadersRead = 1,
    }
}